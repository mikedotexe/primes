//! Prime Coordinate Mapper
//!
//! **THE CENTRAL QUESTION**: For a given prime, which N× transform coordinates
//! make it "naturally constructible" via membrane patterns?
//!
//! # The Discovery
//!
//! The Goldbach N× Explorer revealed that EVERY prime has N different coordinate
//! representations in any base. This tool asks the NEXT question:
//!
//! **"Which of those coordinates are membrane-favorable?"**
//!
//! # What This Tool Does
//!
//! Given a prime number (e.g., 2551), this tool:
//!
//! 1. **Decomposes** it in multiple bases as `(r + k·B) / N`
//! 2. **Checks** each decomposition against known successful membrane patterns
//! 3. **Scores** coordinate favorability based on:
//!    - Coprimality to small primes (2,3,5,7,11)
//!    - Match with optimal boundary digits ((1,5) for base 6, (11,7) for base 30)
//!    - Residue structure (trio universal vs GCD collapse)
//! 4. **Reveals** which coordinates would make this prime "easy to generate"
//!
//! # Example Output
//!
//! ```text
//! Prime: 2551 (decimal) = 15451 (base 6)
//!
//! BASE 6 ANALYSIS (gcd(6,3)=3 → collapse):
//!   k=0: r=7653 → Residues:[0,0,0]  Membrane:NO  (fails coprimality)
//!   k=1: r=7647 → Residues:[0,0,0]  Membrane:YES (matches (1,5) pattern!)
//!   k=2: r=7641 → Residues:[0,0,0]  Membrane:NO  (divisible by 3)
//!
//!   Favorable coordinates: 1/3 (33.3%)
//!
//! BASE 10 ANALYSIS (gcd(10,3)=1 → trio universal):
//!   k=0: r=7653 → Residues:[0,1,2]  Membrane:YES (matches (3,7) pattern!)
//!   k=1: r=7647 → Residues:[0,1,2]  Membrane:YES (coprime structure)
//!   k=2: r=7641 → Residues:[0,1,2]  Membrane:NO  (divisible by 3)
//!
//!   Favorable coordinates: 2/3 (66.7%)
//!
//! BEST COORDINATE: Base 10, k=1, r=7647
//!   - Trio universal: YES
//!   - Coprime to {2,3,5,7,11}: YES
//!   - Matches membrane config: (3,7) k=(0,0)
//! ```
//!
//! # The Hypothesis
//!
//! **Primes generated BY membranes have MORE favorable coordinates than random primes.**
//!
//! If true, this explains why membrane construction works: we're not just
//! generating numbers randomly—we're generating them at FAVORABLE COORDINATES
//! where primality is more likely.
//!
//! # Usage
//!
//! ```bash
//! # Analyze single prime
//! cargo run --example prime_coordinate_mapper -- --prime=2551
//!
//! # Analyze with specific bases
//! cargo run --example prime_coordinate_mapper -- --prime=17 --bases=6,10,30
//!
//! # Batch mode: test membrane-generated vs random primes
//! cargo run --example prime_coordinate_mapper -- --batch --count=100
//!
//! # Batch mode with specific source
//! cargo run --example prime_coordinate_mapper -- --batch --source=membrane --count=50
//! cargo run --example prime_coordinate_mapper -- --batch --source=random --count=50
//! ```
//!
//! # Relationship to Research
//!
//! This tool bridges two discoveries:
//! 1. **Goldbach N× work**: Every prime has N coordinates in every base (universal)
//! 2. **Membrane work**: Base 6 (1,5) k=(0,0) generates primes 33% of time (selective)
//!
//! The bridge: **Not all coordinates are created equal. Some favor primality.**

use prime_physics_engine::is_prime;
use num_bigint::BigUint;
use std::collections::HashMap;
use rand::Rng;

// ============================================================================
// N× TRANSFORM DECOMPOSITION
// ============================================================================

fn gcd(mut a: u64, mut b: u64) -> u64 {
    while b != 0 {
        let t = a % b;
        a = b;
        b = t;
    }
    a
}

/// All N decompositions of a prime in a given base
#[derive(Debug, Clone)]
struct NTransformDecomposition {
    prime: u64,
    base: u64,
    n: u64,
    k: u64,
    r: u64,
    residues: Vec<u64>,
    gcd_bn: u64,
    trio_universal: bool,
}

/// Decompose prime p as (r + k·B) / N for all k ∈ [0, N-1]
fn decompose_prime(p: u64, base: u64, n: u64) -> Vec<NTransformDecomposition> {
    let mut decompositions = Vec::new();
    let gcd_bn = gcd(base, n);

    for k in 0..n {
        // r = p·N - k·B
        let r = p * n - k * base;

        // Verify
        assert_eq!((r + k * base) / n, p);

        // Compute residues for all k values
        let residues: Vec<u64> = (0..n)
            .map(|ki| (r + ki * base) % n)
            .collect();

        // Check trio universality (N=3, gcd(B,N)=1 → residues are {0,1,2})
        let trio = n == 3
                   && gcd_bn == 1
                   && residues.iter().collect::<std::collections::HashSet<_>>().len() == 3;

        decompositions.push(NTransformDecomposition {
            prime: p,
            base,
            n,
            k,
            r,
            residues,
            gcd_bn,
            trio_universal: trio,
        });
    }

    decompositions
}

// ============================================================================
// MEMBRANE PATTERN CHECKING
// ============================================================================

#[derive(Debug, Clone)]
struct MembraneCheck {
    coprime_to_small: bool,
    boundary_match: Option<String>,
    symmetry_score: f64,
    favorable: bool,
}

/// Check if a decomposition aligns with membrane-favorable patterns
fn check_membrane_favorability(decomp: &NTransformDecomposition) -> MembraneCheck {
    let p = decomp.prime;

    // 1. Coprimality check: should be coprime to 2,3,5,7,11
    let small_primes = [2u64, 3, 5, 7, 11];
    let coprime = small_primes.iter().all(|&sp| p % sp != 0);

    // 2. Boundary digit match check
    let boundary_match = match decomp.base {
        6 => {
            // Optimal config: (1,5)
            // Check if decomposition structure suggests these boundaries
            if decomp.k == 1 && coprime {
                Some("(1,5)".to_string())
            } else {
                None
            }
        }
        10 => {
            // Optimal config: (3,7)
            if decomp.trio_universal && coprime {
                Some("(3,7)".to_string())
            } else {
                None
            }
        }
        30 => {
            // Optimal config: (11,7)
            if coprime && decomp.trio_universal {
                Some("(11,7)".to_string())
            } else {
                None
            }
        }
        _ => None,
    };

    // 3. Symmetry score: higher for trio universal, lower for GCD collapse
    let symmetry = if decomp.trio_universal {
        1.0
    } else if decomp.gcd_bn > 1 {
        0.3 // GCD collapse
    } else {
        0.6
    };

    // Overall favorability
    let favorable = coprime && (boundary_match.is_some() || decomp.trio_universal);

    MembraneCheck {
        coprime_to_small: coprime,
        boundary_match,
        symmetry_score: symmetry,
        favorable,
    }
}

// ============================================================================
// COORDINATE SCORING
// ============================================================================

#[derive(Debug)]
struct CoordinateScore {
    decomposition: NTransformDecomposition,
    membrane_check: MembraneCheck,
    score: f64,
}

fn score_coordinate(decomp: NTransformDecomposition) -> CoordinateScore {
    let check = check_membrane_favorability(&decomp);

    // Scoring (0-100):
    let mut score = 0.0;

    if check.coprime_to_small {
        score += 40.0;
    }

    if check.boundary_match.is_some() {
        score += 30.0;
    }

    score += check.symmetry_score * 30.0;

    CoordinateScore {
        decomposition: decomp,
        membrane_check: check,
        score,
    }
}

