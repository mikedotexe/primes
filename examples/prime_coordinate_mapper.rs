// ============================================================================

fn generate_membrane_prime(base: u64, seed: u64) -> Option<u64> {
    // Simple membrane generation (outer,inner) = (1,5) for base 6, (3,7) for base 10
    let (outer, inner) = match base {
        6 => (1, 5),
        10 => (3, 7),
        30 => (11, 7),
        _ => return None,
    };

    // Format: outer + inner + seed + inner + outer (no padding for simplicity)
    let membrane_str = format!("{}{}{}{}{}", outer, inner, seed, inner, outer);

    if let Ok(num) = membrane_str.parse::<u64>() {
        if num > 1 && is_prime(&BigUint::from(num)) {
            return Some(num);
        }
    }

    None
}

fn generate_random_prime(max: u64) -> u64 {
    let mut rng = rand::thread_rng();

    loop {
        let candidate = rng.gen_range(100..max);
        if is_prime(&BigUint::from(candidate)) {
            return candidate;
        }
    }
}

#[derive(Debug)]
struct BatchResults {
    source: String,
    primes_analyzed: usize,
    avg_favorable_coords: HashMap<u64, f64>,
}

fn batch_analyze(source: &str, count: usize, bases: &[u64]) -> BatchResults {
    let mut total_favorable: HashMap<u64, usize> = HashMap::new();
    let mut primes_analyzed = 0;

    println!("Generating {} {} primes for batch analysis...", count, source);

    for i in 0..count {
        let prime = match source {
            "membrane" => {
                // Try base 10 membrane generation
                let seed = (i * 7 + 3) as u64 % 9 + 1;
                if let Some(p) = generate_membrane_prime(10, seed) {
                    p
                } else {
                    continue;
                }
            }
            "random" => generate_random_prime(10000),
            _ => continue,
        };

        primes_analyzed += 1;

        // Analyze in each base
        for &base in bases {
            let decomps = decompose_prime(prime, base, 3);
            let favorable_count = decomps.iter()
                .filter(|d| check_membrane_favorability(d).favorable)
                .count();

            *total_favorable.entry(base).or_insert(0) += favorable_count;
        }

        if primes_analyzed % 10 == 0 {
            print!(".");
            use std::io::Write;
            std::io::stdout().flush().ok();
        }
    }

    println!();

    // Calculate averages
    let avg_favorable: HashMap<u64, f64> = total_favorable.iter()
        .map(|(&base, &total)| {
            (base, total as f64 / primes_analyzed as f64)
        })
        .collect();

    BatchResults {
        source: source.to_string(),
        primes_analyzed,
        avg_favorable_coords: avg_favorable,
    }
}

