//! Export canonical matched-control family lanes as a Lean artifact.

use clap::Parser;
use primes::validation::{
    matched_control::{
        matched_control_lean_lane_name, MatchedControlFamily, MatchedControlPanel,
        MAINTAINED_MATCHED_CONTROL_FAMILIES,
    },
    reporting::write_text_file,
};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

#[derive(Parser, Debug)]
#[command(
    author,
    version,
    about = "Export maintained matched-control family lanes as a Lean artifact"
)]
struct Args {
    /// Canonical matched-control panel to expand into Lean lanes.
    #[arg(long, default_value = "smoke")]
    panel: String,

    /// Output path under lean-proofs/PrimeArithmetic/Generated/.
    #[arg(long)]
    out: Option<PathBuf>,
}

#[derive(Debug, Clone)]
struct LaneRow {
    name: String,
    family: MatchedControlFamily,
    middle_width: usize,
    family_code: String,
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let args = Args::parse();
    let panel = MatchedControlPanel::from_name(&args.panel)
        .ok_or("invalid --panel value; expected smoke or audit")?;
    let output_path = resolve_output_path(&args)?;
    let module_name = lean_module_name(&output_path)?;
    let lanes = build_lane_rows(panel);
    let artifact = render_artifact(panel, &lanes, &module_name, &args)?;

    write_text_file(&output_path, &artifact)?;

    println!("Wrote Lean artifact: {}", display_path(&output_path));
    println!("Module: {module_name}");
    println!("Panel: {} ({})", panel.panel_id(), panel.as_str());
    println!("Lanes: {}", lanes.len());

    Ok(())
}

fn build_lane_rows(panel: MatchedControlPanel) -> Vec<LaneRow> {
    let settings = panel.settings();
    MAINTAINED_MATCHED_CONTROL_FAMILIES
        .iter()
        .flat_map(|family| {
            (settings.min_seed_len..=settings.max_seed_len).map(move |middle_width| LaneRow {
                name: matched_control_lean_lane_name(family, middle_width),
                family: *family,
                middle_width,
                family_code: family.code(middle_width),
            })
        })
        .collect()
}

fn resolve_output_path(args: &Args) -> Result<PathBuf, Box<dyn std::error::Error>> {
    let repo_root = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let output = args.out.clone().unwrap_or_else(|| {
        PathBuf::from("lean-proofs")
            .join("PrimeArithmetic")
            .join("Generated")
            .join("MatchedControlFamilyLanes.lean")
    });
    let absolute = if output.is_absolute() {
        output
    } else {
        repo_root.join(output)
    };

    let lean_root = repo_root.join("lean-proofs");
    let generated_root = lean_root.join("PrimeArithmetic").join("Generated");
    if !absolute.starts_with(&generated_root) {
        return Err(format!("output path must live under {}", generated_root.display()).into());
    }
    if absolute.extension().and_then(|ext| ext.to_str()) != Some("lean") {
        return Err("output path must end with .lean".into());
    }
    Ok(absolute)
}

fn lean_module_name(path: &Path) -> Result<String, Box<dyn std::error::Error>> {
    let repo_root = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let lean_root = repo_root.join("lean-proofs");
    let relative = path
        .strip_prefix(&lean_root)
        .map_err(|_| "output path is not inside lean-proofs")?;
    let without_ext = relative.with_extension("");
    let components: Vec<String> = without_ext
        .components()
        .map(|component| component.as_os_str().to_string_lossy().to_string())
        .collect();
    if components.is_empty() {
        return Err("could not derive a Lean module name from the output path".into());
    }
    Ok(components.join("."))
}

fn render_artifact(
    panel: MatchedControlPanel,
    lanes: &[LaneRow],
    module_name: &str,
    args: &Args,
) -> Result<String, Box<dyn std::error::Error>> {
    let mut out = String::new();
    let command = format!(
        "cargo run --bin export_matched_control_family_lanes -- --panel {} --out {}",
        panel.as_str(),
        default_display_output(args)
    );

    writeln!(
        out,
        "import PrimeArithmetic.Structure.BoundedKResidueProfile"
    )?;
    writeln!(out)?;
    writeln!(out, "namespace {module_name}")?;
    writeln!(out)?;
    writeln!(out, "open PrimeArithmetic.Structure")?;
    writeln!(out)?;
    writeln!(out, "/-!")?;
    writeln!(out, "Runtime-exported matched-control family-lane catalog.")?;
    writeln!(out)?;
    writeln!(out, "Generated by:")?;
    writeln!(out, "`{command}`")?;
    writeln!(out)?;
    writeln!(
        out,
        "- panel: `{}` (`{}`)",
        panel.panel_id(),
        panel.as_str()
    )?;
    writeln!(
        out,
        "- maintained family count: `{}`",
        MAINTAINED_MATCHED_CONTROL_FAMILIES.len()
    )?;
    writeln!(out, "- exported lane count: `{}`", lanes.len())?;
    writeln!(out, "-/")?;
    writeln!(out)?;
    writeln!(
        out,
        "def panelId : String := {}",
        lean_string(panel.panel_id())
    )?;
    writeln!(out)?;

    for lane in lanes {
        writeln!(out, "def {} : BoundedKFamilyLane where", lane.name)?;
        writeln!(out, "  familyCode := {}", lean_string(&lane.family_code))?;
        writeln!(out, "  base := {}", lane.family.base)?;
        writeln!(out, "  outer := {}", lane.family.outer)?;
        writeln!(out, "  inner := {}", lane.family.inner)?;
        writeln!(out, "  middleWidth := {}", lane.middle_width)?;
        writeln!(
            out,
            "  cfg := ({{ kOuter := {}, kInner := {} }} : BoundedKConfig)",
            lane.family.k_outer, lane.family.k_inner
        )?;
        writeln!(out)?;
    }

    writeln!(out, "def lanes : List BoundedKFamilyLane := [")?;
    for lane in lanes {
        writeln!(out, "  {},", lane.name)?;
    }
    writeln!(out, "]")?;
    writeln!(out)?;
    writeln!(
        out,
        "def laneKey (lane : BoundedKFamilyLane) : String × ℕ :="
    )?;
    writeln!(out, "  (lane.familyCode, lane.middleWidth)")?;
    writeln!(out)?;
    writeln!(out, "def laneKeys : List (String × ℕ) :=")?;
    writeln!(out, "  lanes.map laneKey")?;
    writeln!(out)?;
    writeln!(
        out,
        "def laneKeyMatches (familyCode : String) (middleWidth : ℕ) (lane : BoundedKFamilyLane) : Bool :="
    )?;
    writeln!(
        out,
        "  (lane.familyCode == familyCode) && (lane.middleWidth == middleWidth)"
    )?;
    writeln!(out)?;
    writeln!(
        out,
        "def lookupByFamilyCodeAndMiddleWidth (familyCode : String) (middleWidth : ℕ) : Option BoundedKFamilyLane :="
    )?;
    writeln!(out, "  lanes.find? (laneKeyMatches familyCode middleWidth)")?;
    writeln!(out)?;
    writeln!(
        out,
        "theorem panelId_value : panelId = {} := rfl",
        lean_string(panel.panel_id())
    )?;
    writeln!(out)?;
    writeln!(
        out,
        "theorem laneCount_value : lanes.length = {} := by",
        lanes.len()
    )?;
    writeln!(out, "  native_decide")?;
    writeln!(out)?;
    writeln!(out, "theorem lanes_nodup : lanes.Nodup := by")?;
    writeln!(out, "  native_decide")?;
    writeln!(out)?;
    writeln!(out, "theorem laneKeys_nodup : laneKeys.Nodup := by")?;
    writeln!(out, "  native_decide")?;

    for lane in lanes {
        writeln!(out)?;
        writeln!(
            out,
            "theorem {}_key : laneKey {} = ({}, {}) := rfl",
            lane.name,
            lane.name,
            lean_string(&lane.family_code),
            lane.middle_width
        )?;
        writeln!(out)?;
        writeln!(
            out,
            "theorem {}_mem_lanes : {} ∈ lanes := by",
            lane.name, lane.name
        )?;
        writeln!(out, "  simp [lanes]")?;
        writeln!(out)?;
        writeln!(
            out,
            "theorem {}_lookup : lookupByFamilyCodeAndMiddleWidth {} {} = some {} := by",
            lane.name,
            lean_string(&lane.family_code),
            lane.middle_width,
            lane.name
        )?;
        writeln!(out, "  native_decide")?;
    }

    writeln!(out)?;
    writeln!(out, "end {module_name}")?;
    Ok(out)
}

fn lean_string(value: &str) -> String {
    let escaped = value
        .replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('\n', "\\n");
    format!("\"{escaped}\"")
}

fn default_display_output(args: &Args) -> String {
    args.out
        .as_ref()
        .map(|path| display_path(path))
        .unwrap_or_else(|| {
            "lean-proofs/PrimeArithmetic/Generated/MatchedControlFamilyLanes.lean".to_string()
        })
}

fn display_path(path: &Path) -> String {
    let repo_root = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    path.strip_prefix(&repo_root)
        .unwrap_or(path)
        .display()
        .to_string()
}
